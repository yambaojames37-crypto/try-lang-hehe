a = int(input("Enter the first number: "))
b = int(input("Enter the second number: "))
c = str(input("Enter the opertor(+, -, *, /): "))

if c == "+":
    print(a+b)

elif c == "-":
    print(a-b)

elif c == "*":
    print(a*b)

elif c == "/":
    print(a/b)
    
else:
    print(" ENGKK_ERROR ")